func TestExtractPackageDocStripsGeneratedBanner(t *testing.T) {
	dir := t.TempDir()
	// Banner sits in the same doc group (no blank line) directly above the
	// package clause, so it IS part of f.Doc — cleanDoc must drop it.
	writeGoFile(t, dir, "schema.gen.go", `// Code generated by protoc-gen-go. DO NOT EDIT.
// Package schema defines the wire schema.
package schema
`)
	res, err := ExtractPackageDoc(dir, []string{"schema.gen.go"})
	if err != nil {
		t.Fatalf("ExtractPackageDoc: %v", err)
	}
	if strings.Contains(res.GodocText, "DO NOT EDIT") || strings.Contains(res.GodocText, "Code generated") {
		t.Errorf("generated banner leaked into GodocText: %q", res.GodocText)
	}
	if res.GodocText != "defines the wire schema." {
		t.Errorf("GodocText = %q, want %q", res.GodocText, "defines the wire schema.")
	}
}

// TestExtractPackageDocSplitFiles covers the cross-file merge: godoc lives
// in doc.go, the //observer:summary + task directives in pipeline.go. The
// summary must still win over the godoc even though they're in different
// files (precedence holds across the split).
func TestExtractPackageDocSplitFiles(t *testing.T) {
	dir := t.TempDir()
	writeGoFile(t, dir, "doc.go", `// Package proc does the processing.
package proc
`)
	writeGoFile(t, dir, "pipeline.go", `//observer:summary Runs the processing pipeline end to end.
//observer:task OBS-9
package proc

func Run() {}
`)
	res, err := ExtractPackageDoc(dir, []string{"doc.go", "pipeline.go"})
	if err != nil {
		t.Fatalf("ExtractPackageDoc: %v", err)
	}
	if res.GodocText != "does the processing." {
		t.Errorf("GodocText = %q, want %q", res.GodocText, "does the processing.")
	}
	if res.Summary != "Runs the processing pipeline end to end." {
		t.Errorf("Summary = %q (must be read from pipeline.go)", res.Summary)
	}
	if res.Task != "OBS-9" {
		t.Errorf("Task = %q", res.Task)
	}
	// PrimaryFile tracks the godoc source, not the annotation file.
	if res.PrimaryFile != "doc.go" {
		t.Errorf("PrimaryFile = %q, want doc.go", res.PrimaryFile)
	}
}

func TestInferLinkType(t *testing.T) {
	cases := map[string]string{
		"SP-142":  "serviceplus", // SP prefix stays serviceplus even though it matches the Jira shape
		"OBS-42":  "jira",
		"PLAT-7":  "jira",
		"ticket1": "serviceplus", // doesn't match [A-Z]+-\d+ at all
		"":        "serviceplus",
	}
	for task, want := range cases {
		if got := InferLinkType(task); got != want {
			t.Errorf("InferLinkType(%q) = %q, want %q", task, got, want)
		}
	}
}
